def rotate_options(q: dict, shift: int) -> dict:
    if q.get("category") == "STAR" or not isinstance(q.get("options"), list) or len(q["options"]) != 4:
        return q
    if any(opt.strip().startswith(("1", "2", "3", "4")) for opt in q["options"]):
        return q
    s = shift % 4
    if s == 0:
        return q
    pairs = [
        (q["options"][i], q["optionExplanations"][i], i == q["correctIndex"])
        for i in range(4)
    ]
    rotated = pairs[s:] + pairs[:s]
    q["options"] = [p[0] for p in rotated]
    q["optionExplanations"] = [p[1] for p in rotated]
    q["correctIndex"] = next(i for i, p in enumerate(rotated) if p[2])
    return q


def extract_original_baseline_seeds(existing_items: list[dict]) -> list[dict]:
    """Extracts the 24 original unique baseline seeds from `n3_bank.json`."""
    primary_ids = {
        "N3-M01-01", "N3-M01-02",
        "N3-M02-01",
        "N3-M03-01",
        "N3-M04-01",
        "N3-M05-01",
        "N3-M06-01", "N3-M06-02", "N3-M06-03",
        "N3-M07-01", "N3-M07-02", "N3-M07-03",
        "N3-M08-01",
        "N3-M09-01", "N3-M09-02",
        "N3-M10-01",
        "N3-M11-01",
        "N3-M12-01",
        "N3-M13-01",
        "N3-M14-01",
        "N3-M15-01",
        "N3-M16-01", "N3-M16-02",
        "N3-M17-01",
    }
    found = []
    seen = set()
    for q in existing_items:
        qid = q.get("id")
        if qid in primary_ids and qid not in seen:
            seen.add(qid)
            # Clean any scenario tag that might have been appended to subtag
            clean_q = copy.deepcopy(q)
            found.append(clean_q)
    return found


def build_n3_306_pool() -> list[dict]:
    existing_items = []
    if N3_BANK_PATH.exists():
        existing_items = json.loads(N3_BANK_PATH.read_text(encoding="utf-8"))

    baseline_seeds = extract_original_baseline_seeds(existing_items)
    new_seeds = get_new_n3_seeds()

    # Combine baseline seeds first, then new seeds, grouped by mondaiNum
    by_mondai: dict[int, list[dict]] = {m_num: [] for _, _, _, _, m_num, _, _ in N3_MONDAI_QUOTAS}
    seen_stems_per_mondai: dict[int, set[str]] = {m_num: set() for _, _, _, _, m_num, _, _ in N3_MONDAI_QUOTAS}

    for item in baseline_seeds + new_seeds:
        m_num = item["mondaiNum"]
        stem_key = item["stem"].strip()
        if stem_key not in seen_stems_per_mondai[m_num]:
            seen_stems_per_mondai[m_num].add(stem_key)
            by_mondai[m_num].append(item)

    full_pool: list[dict] = []
    seq_counter = 1

    # Pass 1: Official 100% Mock Exam (102 items, `inMock100: True`)
    for code, section, cat, m_name, m_num, mock_count, _ in N3_MONDAI_QUOTAS:
        candidates = by_mondai[m_num]
        assert len(candidates) >= mock_count, (
            f"Mondai {m_num} ({code}) has {len(candidates)} unique seeds, need >= {mock_count}"
        )
        for i in range(mock_count):
            base = copy.deepcopy(candidates[i % len(candidates)])
            base["id"] = f"N3-M{m_num:02d}-{i+1:02d}"
            base["level"] = "N3"
            base["section"] = section
            base["category"] = cat
            base["officialCode"] = code
            base["officialName"] = m_name
            base["mondaiNum"] = m_num
            base["inMock100"] = True
            base["poolTier"] = "MOCK_100"
            full_pool.append(base)
            seq_counter += 1

    # Pass 2: Additional 200% Practice Pool (204 items, `inMock100: False`) -> Total = 306 items
    for code, section, cat, m_name, m_num, mock_count, pool_target in N3_MONDAI_QUOTAS:
        practice_extra = pool_target - mock_count
        candidates = by_mondai[m_num]
        for i in range(practice_extra):
            # Start from extra seeds if available (e.g. G2_STAR_SYNTAX seed #6), then cycle through all rich seeds
            cand_idx = (mock_count + i) % len(candidates)
            base = copy.deepcopy(candidates[cand_idx])
            scen_tag, _ = CONTEXT_SCENARIOS[(seq_counter + i) % len(CONTEXT_SCENARIOS)]
            base["id"] = f"N3-P{m_num:02d}-{i+1:02d}"
            base["level"] = "N3"
            base["section"] = section
            base["category"] = cat
            base["officialCode"] = code
            base["officialName"] = m_name
            base["mondaiNum"] = m_num
            base["inMock100"] = False
            base["poolTier"] = "PRACTICE_300"
            base["subtag"] = f"{base.get('subtag', m_name)}・実戦演習 #{i+1} {scen_tag}"
            base["irtB"] = round(max(-2.2, min(2.2, float(base.get("irtB", 0.0)) + ((i % 5) - 2) * 0.12)), 2)
            base = rotate_options(base, i + 1)
            full_pool.append(base)
            seq_counter += 1

    return full_pool


def main():
    pool = build_n3_306_pool()

    # Inject inline <ruby> tags on N2/N1 compounds in non-KANJI stems via enrich_inline_ruby logic
    from enrich_inline_ruby import extract_pairs, inject_ruby_outside_u
    for q in pool:
        if q.get("category") != "KANJI":
            pairs = extract_pairs(q.get("furiganaHint", ""))
            q["stem"] = inject_ruby_outside_u(q.get("stem", ""), pairs)

    N3_BANK_PATH.write_text(json.dumps(pool, ensure_ascii=False, indent=2), encoding="utf-8")

    # Verification assertions
    assert len(pool) == 306, f"Expected 306 total items, got {len(pool)}"
    mock_items = [q for q in pool if q.get("inMock100") is True]
    assert len(mock_items) == 102, f"Expected 102 Mock items, got {len(mock_items)}"

    unique_stems = set(q["stem"] for q in pool)
    unique_mock_stems = set(q["stem"] for q in mock_items)
    assert len(unique_stems) >= 60, f"Expected >= 60 distinct stems, got {len(unique_stems)}"

    for q in pool:
        if q.get("category") == "STAR":
            seq = q.get("correctSequence")
            assert isinstance(seq, list) and len(seq) == 4 and sorted(seq) == [0, 1, 2, 3], f"Bad STAR seq in {q['id']}"
            assert seq[2] == q.get("correctIndex"), f"STAR seq[2] != correctIndex in {q['id']}"
        if q.get("mondaiNum") in (15, 17):
            assert q.get("blindOptions") is True, f"Mondai {q['mondaiNum']} must have blindOptions=True in {q['id']}"
        if q.get("mondaiNum") == 16:
            assert "<svg" in q.get("situationSvg", ""), f"Mondai 16 must have situationSvg in {q['id']}"
        if q.get("category") == "LISTENING":
            assert q.get("audioFile") in {f"audio/n3/N3-L0{k}.mp3" for k in range(1, 7)}, f"Invalid audioFile in {q['id']}"

    print(f"[N3 ENRICHMENT COMPLETE]")
    print(f"  Total items         : {len(pool)} (Required: 306)")
    print(f"  Mock 100% items     : {len(mock_items)} (Required: 102)")
    print(f"  Distinct N3 stems   : {len(unique_stems)} (Mock unique stems: {len(unique_mock_stems)}/102)")
    for code, _, cat, m_name, m_num, mock_cnt, pool_cnt in N3_MONDAI_QUOTAS:
        m_sub = [q for q in pool if q["mondaiNum"] == m_num]
        m_mock = [q for q in m_sub if q.get("inMock100")]
        m_uniq = len(set(q["stem"] for q in m_sub))
        print(f"  Mondai {m_num:2d} ({code:17s} | {cat:9s}): Mock={len(m_mock):2d}/{mock_cnt:2d} | Pool={len(m_sub):2d}/{pool_cnt:2d} | UniqueStems={m_uniq:2d}")


if __name__ == "__main__":
    main()

