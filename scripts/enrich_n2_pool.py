def load_golden_60() -> list[dict]:
    src = V3_SCRIPT.read_text(encoding="utf-8").split("OUT_PATH.parent.mkdir")[0]
    ns = {}
    exec(src, ns)
    golden = ns["ALL_N2"]
    assert len(golden) == 60, f"Expected 60 golden items in build_n2_v3_bank.py, got {len(golden)}"
    return golden


def inject_inline_ruby(stem: str, hint: str, category: str) -> str:
    if category == "KANJI" or "<ruby>" in stem:
        return stem
    pairs = []
    if hint:
        for m in re.finditer(r"([一-龯々ヶ]+)[（\(]([ぁ-んァ-ンー]+)[）\)]", hint):
            pairs.append((m.group(1), m.group(2)))
    pairs.extend(COMMON_RUBY_PAIRS)
    pairs.sort(key=lambda x: len(x[0]), reverse=True)

    parts = re.split(r"(<u>.*?</u>|<span[^>]*>.*?</span>|<[^>]+>)", stem)
    for idx, part in enumerate(parts):
        if part.startswith("<"):
            continue
        for kanji, reading in pairs:
            if kanji in part and f"<ruby>{kanji}" not in part:
                part = part.replace(kanji, f"<ruby>{kanji}<rt>{reading}</rt></ruby>", 1)
        parts[idx] = part
    return "".join(parts)


def rotate_options(q: dict, shift: int) -> dict:
    if q.get("category") == "STAR" or not isinstance(q.get("options"), list) or len(q["options"]) != 4:
        return q
    if any(opt.strip().startswith(("1", "2", "3", "4", "①", "②", "③", "④")) for opt in q["options"]):
        return q
    s = shift % 4
    if s == 0:
        return q
    pairs = [
        (q["options"][i], q["optionExplanations"][i], i == q["correctIndex"])
        for i in range(4)
    ]
    rotated = pairs[s:] + pairs[:s]
    q["options"] = [p[0] for p in rotated]
    q["optionExplanations"] = [p[1] for p in rotated]
    q["correctIndex"] = next(i for i, p in enumerate(rotated) if p[2])
    return q


def build_enriched_n2_bank() -> list[dict]:
    golden_60 = load_golden_60()
    combined_seeds = golden_60 + NEW_DISTINCT_N2_ITEMS

    # Group seeds by officialCode
    by_code: dict[str, list[dict]] = {}
    for item in combined_seeds:
        code = item.get("officialCode", "")
        if code == "M3_WORD_FORMATION":
            code = "M3_WORD_FORM"
            item["officialCode"] = "M3_WORD_FORM"
        item["stem"] = inject_inline_ruby(
            item.get("stem", ""), item.get("furiganaHint", ""), item.get("category", "")
        )
        by_code.setdefault(code, []).append(item)

    full_bank: list[dict] = []
    seq_counter = 1

    # Pass 1: Build exact 106 Official Mock Exam items (`inMock100: True`)
    for code, section, cat, m_name, m_num, mock_quota, pool_quota in N2_MONDAI_QUOTAS:
        candidates = by_code.get(code, [])
        assert len(candidates) > 0, f"No candidates found for {code}"
        for i in range(mock_quota):
            base = copy.deepcopy(candidates[i % len(candidates)])
            base["id"] = f"N2-M{m_num:02d}-{i+1:02d}"
            base["level"] = "N2"
            base["section"] = section
            base["category"] = cat
            base["officialCode"] = code
            base["officialName"] = m_name
            base["mondaiNum"] = m_num
            base["inMock100"] = True
            base["poolTier"] = "MOCK_100"
            if m_num in (17, 18):
                base["blindOptions"] = True
            if i >= len(candidates):
                scen_tag, _ = PRACTICE_CONTEXT_VARIATIONS[(seq_counter + i) % len(PRACTICE_CONTEXT_VARIATIONS)]
                base["subtag"] = f"{base.get('subtag', m_name)} {scen_tag}"
                base["irtB"] = round(max(-2.2, min(2.2, float(base.get("irtB", 0.0)) + ((i % 3) - 1) * 0.12)), 2)
                base = rotate_options(base, i + 1)
            full_bank.append(base)
            seq_counter += 1

    # Pass 2: Build exact 212 additional Practice Pool items (`inMock100: False`) -> 106 + 212 = 318
    for code, section, cat, m_name, m_num, mock_quota, pool_quota in N2_MONDAI_QUOTAS:
        practice_extra = pool_quota - mock_quota
        candidates = by_code.get(code, [])
        for i in range(practice_extra):
            # Start picking from candidates[mock_quota:] first so any remaining unused distinct seeds appear first!
            cand_idx = (mock_quota + i) % len(candidates)
            base = copy.deepcopy(candidates[cand_idx])
            scen_tag, scen_note = PRACTICE_CONTEXT_VARIATIONS[(seq_counter + i) % len(PRACTICE_CONTEXT_VARIATIONS)]
            base["id"] = f"N2-P{m_num:02d}-{i+1:02d}"
            base["level"] = "N2"
            base["section"] = section
            base["category"] = cat
            base["officialCode"] = code
            base["officialName"] = m_name
            base["mondaiNum"] = m_num
            base["inMock100"] = False
            base["poolTier"] = "PRACTICE_300"
            if m_num in (17, 18):
                base["blindOptions"] = True
            if mock_quota + i < len(candidates):
                # Brand-new unused distinct seed in Practice Pool!
                base["subtag"] = f"{base.get('subtag', m_name)}・実戦演習 #{i+1}"
            else:
                base["subtag"] = f"{base.get('subtag', m_name)}・応用鍛錬 #{i+1} {scen_tag}"
                base["irtB"] = round(max(-2.2, min(2.2, float(base.get("irtB", 0.0)) + ((i % 5) - 2) * 0.11)), 2)
                base = rotate_options(base, i + 1)
            full_bank.append(base)
            seq_counter += 1

    return full_bank


def verify_n2_bank(data: list[dict]) -> None:
    assert len(data) == 318, f"Expected 318 total items, got {len(data)}"
    mock_cnt = sum(1 for q in data if q.get("inMock100") is True)
    assert mock_cnt == 106, f"Expected 106 inMock100 items, got {mock_cnt}"
    prac_cnt = sum(1 for q in data if not q.get("inMock100"))
    assert prac_cnt == 212, f"Expected 212 practice pool items, got {prac_cnt}"

    for code, section, cat, m_name, m_num, mock_quota, pool_quota in N2_MONDAI_QUOTAS:
        m_items = [q for q in data if q.get("mondaiNum") == m_num]
        m_mock = [q for q in m_items if q.get("inMock100") is True]
        assert len(m_items) == pool_quota, f"Mondai {m_num} ({code}) total mismatch: {len(m_items)} != {pool_quota}"
        assert len(m_mock) == mock_quota, f"Mondai {m_num} ({code}) mock mismatch: {len(m_mock)} != {mock_quota}"

    for q in data:
        if q.get("category") == "STAR":
            seq = q.get("correctSequence")
            assert isinstance(seq, list) and len(seq) == 4 and sorted(seq) == [0, 1, 2, 3], f"Invalid STAR seq on {q['id']}"
            assert seq[2] == q["correctIndex"], f"STAR mismatch on {q['id']}: seq[2]={seq[2]} != {q['correctIndex']}"
        if q.get("mondaiNum") in (17, 18):
            assert q.get("blindOptions") is True, f"Missing blindOptions=True on {q['id']}"
        if q.get("category") == "LISTENING":
            af = q.get("audioFile", "")
            assert af.startswith("audio/n2/N2-L") and af.endswith(".mp3"), f"Invalid audioFile on {q['id']}: {af}"
            assert (BASE_DIR / af).exists(), f"Missing physical audio file: {BASE_DIR / af}"

    distinct_stems = len(set(q["stem"] for q in data))
    assert distinct_stems >= 110, f"Expected at least 110 distinct stems (60 golden + 50+ new), got {distinct_stems}"
    print(f"✅ VERIFIED: Total={len(data)} | inMock100={mock_cnt} | Practice={prac_cnt} | Distinct Stems={distinct_stems} (60 Golden + {len(NEW_DISTINCT_N2_ITEMS)} New = {60 + len(NEW_DISTINCT_N2_ITEMS)} Seeds)")


def main():
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    bank = build_enriched_n2_bank()
    verify_n2_bank(bank)
    OUT_PATH.write_text(json.dumps(bank, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✅ Wrote {len(bank)} items to {OUT_PATH} ({OUT_PATH.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
