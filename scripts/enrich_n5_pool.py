def apply_item(q: dict, stem: str, opts: list[str], cidx: int, rule: str, pitch: str):
    q["stem"] = stem
    q["options"] = opts
    q["correctIndex"] = cidx
    q["coreRule"] = rule
    q["pitchAccent"] = pitch
    q["optionExplanations"] = [
        f"✅ 正確解答：{opts[i]}（{rule}）" if i == cidx else f"❌ 誘答陷阱：{opts[i]} 與本題語境或助詞/活用規則不符。"
        for i in range(len(opts))
    ]


def main():
    path = DATA_DIR / "n5_bank.json"
    items = json.loads(path.read_text(encoding="utf-8"))
    for idx, q in enumerate(items):
        cat = q.get("category")
        code = q.get("officialCode")
        if code == "M1_KANJI_READ":
            stem, opts, cidx, rule, pitch = N5_KANJI_READ_BANK[idx % len(N5_KANJI_READ_BANK)]
            apply_item(q, stem, opts, cidx, rule, pitch)
        elif code == "M2_ORTHOGRAPHY":
            stem, opts, cidx, rule, pitch = N5_ORTHOGRAPHY_BANK[idx % len(N5_ORTHOGRAPHY_BANK)]
            apply_item(q, stem, opts, cidx, rule, pitch)
        elif cat == "VOCAB":
            stem, opts, cidx, rule, pitch = N5_VOCAB_BANK[idx % len(N5_VOCAB_BANK)]
            apply_item(q, f"<ruby>次<rt>つぎ</rt></ruby>の文： {stem}", opts, cidx, rule, pitch)
        elif code == "G1_GRAMMAR_FORM":
            stem, opts, cidx, rule, pitch = N5_GRAMMAR_BANK[idx % len(N5_GRAMMAR_BANK)]
            apply_item(q, f"<ruby>明日<rt>あした</rt></ruby>・{stem}", opts, cidx, rule, pitch)
    path.write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Enriched N5 bank: {len(items)} total items | {sum(1 for x in items if x.get('inMock100'))} Mock 100% items")


if __name__ == "__main__":
    main()
